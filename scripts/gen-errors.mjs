#!/usr/bin/env node
// Generates the error-code registry from design/errors.json, one list for every side:
// - HikkiCore/Sources/Errors/ErrorCode.swift — `ErrorCode` (number, "HK-2001", severity, HTTP status)
// - Hikki/Sources/Generated/ErrorMessages.swift — each code's user-facing message (`ErrorCode.message`)
// - editor/src/generated/errors.ts — the same table for the page (`errorMessage`)
// - bff/src/generated/errors.ts — the codes the BFF answers with (status + English message)
// - the messages into both string catalogs (native `app:error.<id>`, web `error.<id>`), en + zh-Hans.
// `--check` fails when any output is stale.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(readFileSync(join(root, 'design/errors.json'), 'utf8'))
const check = process.argv.includes('--check')

const SEVERITIES = ['error', 'warning', 'info']
const RANGES = { 1: 'app', 2: 'pages', 3: 'editor', 4: 'files', 5: 'ai', 6: 'search', 7: 'network' }

const entries = Object.entries(manifest.errors).map(([id, e]) => {
  if (!/^[a-z][A-Za-z0-9]*$/u.test(id)) throw new Error(`bad error id: ${id}`)
  if (!Number.isInteger(e.code) || e.code < 1000 || e.code > 7999)
    throw new Error(`${id}: bad code ${e.code}`)
  if (!RANGES[Math.floor(e.code / 1000)]) throw new Error(`${id}: ${e.code} is in no area`)
  if (!SEVERITIES.includes(e.severity)) throw new Error(`${id}: bad severity ${e.severity}`)
  if (!e.en || !e.zh) throw new Error(`${id}: needs en and zh messages`)
  if (e.http !== undefined && (!Number.isInteger(e.http) || e.http < 400 || e.http > 599))
    throw new Error(`${id}: bad http status ${e.http}`)
  return { id, ...e, area: RANGES[Math.floor(e.code / 1000)] }
})
const numbers = new Map()
for (const e of entries) {
  if (numbers.has(e.code)) throw new Error(`${e.id} and ${numbers.get(e.code)} share ${e.code}`)
  numbers.set(e.code, e.id)
}
if (!entries.some((e) => e.id === 'unknown')) throw new Error('an `unknown` code is required')

const header = (comment) =>
  `${comment} Generated by scripts/gen-errors.mjs from design/errors.json — do not edit.\n`
const swiftString = (s) => JSON.stringify(s)

const swiftCore = `${header('//')}
/// How bad a failure is: \`error\` (it failed, the user should know), \`warning\` (partly failed, degraded), \`info\`.
public enum ErrorSeverity: String, Sendable, Codable {
    case error, warning, info
}

/// Every failure Hikki tells the user about, with a stable number shown as "HK-2001" (in toasts, logs and the
/// diagnostics), so a report names exactly what went wrong.
public enum ErrorCode: String, CaseIterable, Sendable, Codable {
${entries.map((e) => `    case ${e.id}`).join('\n')}

    public var number: Int {
        switch self {
${entries.map((e) => `        case .${e.id}: ${e.code}`).join('\n')}
        }
    }

    /// "HK-2001".
    public var display: String { "HK-\\(number)" }

    /// The area the number belongs to (1xxx app, 2xxx pages & workspace, 3xxx editor, 4xxx files, 5xxx AI,
    /// 6xxx search, 7xxx network).
    public var area: String {
        switch number / 1000 {
${Object.entries(RANGES)
  .map(([k, v]) => `        case ${k}: ${swiftString(v)}`)
  .join('\n')}
        default: "app"
        }
    }

    public var severity: ErrorSeverity {
        switch self {
${entries.map((e) => `        case .${e.id}: .${e.severity}`).join('\n')}
        }
    }

    /// The code for a number (from the BFF or the editor), or nil.
    public init?(number: Int) {
        guard let code = Self.allCases.first(where: { $0.number == number }) else { return nil }
        self = code
    }
}
`

const swiftMessages = `${header('//')}
import HikkiCore

extension ErrorCode {
    /// What the user reads, in the app's language.
    var message: String {
        switch self {
${entries.map((e) => `        case .${e.id}: String(localized: ${swiftString(`app:error.${e.id}`)})`).join('\n')}
        }
    }
}
`

const ts = `${header('//')}
import { t } from '../core/i18n'

export type ErrorSeverity = 'error' | 'warning' | 'info'

/** Every failure Hikki tells the user about (design/errors.json): its number ("HK-2001") and severity. */
export const ERRORS = {
${entries.map((e) => `  ${e.id}: { code: ${e.code}, severity: '${e.severity}' }`).join(',\n')}
} as const satisfies Record<string, { code: number; severity: ErrorSeverity }>

export type ErrorId = keyof typeof ERRORS

/** "HK-2001". */
export const errorDisplay = (id: ErrorId): string => \`HK-\${ERRORS[id].code}\`

/** The code for a number (from the BFF), or \`unknown\`. */
export function errorForCode(code: number | undefined): ErrorId {
  const found = (Object.keys(ERRORS) as ErrorId[]).find((id) => ERRORS[id].code === code)
  return found ?? 'unknown'
}

/** What the user reads, in the page's language. */
export function errorMessage(id: ErrorId): string {
  switch (id) {
${entries.map((e) => `    case '${e.id}':\n      return t('error.${e.id}')`).join('\n')}
  }
}
`

const bffEntries = entries.filter((e) => e.http !== undefined || e.id === 'unknown')
const bff = `${header('//')}
/** The codes the BFF answers with (design/errors.json): number, HTTP status, English message. */
export const ERRORS = {
${bffEntries.map((e) => `  ${e.id}: { code: ${e.code}, status: ${e.http ?? 500}, message: ${JSON.stringify(e.en)} }`).join(',\n')}
} as const

export type ErrorId = keyof typeof ERRORS
`

/** The native catalog with every `app:error.*` key matching the list (others left as they are). */
function nativeCatalog(current) {
  const data = JSON.parse(current)
  for (const key of Object.keys(data.strings))
    if (key.startsWith('app:error.')) delete data.strings[key]
  for (const e of entries) {
    data.strings[`app:error.${e.id}`] = {
      extractionState: 'manual',
      localizations: {
        en: { stringUnit: { state: 'translated', value: e.en } },
        'zh-Hans': { stringUnit: { state: 'translated', value: e.zh } }
      }
    }
  }
  return `${JSON.stringify(sortKeys(data), null, 2)}\n`
}

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys)
  if (value && typeof value === 'object')
    return Object.fromEntries(
      Object.keys(value)
        .toSorted()
        .map((k) => [k, sortKeys(value[k])])
    )
  return value
}

/** A web catalog with its `error` group matching the list (in list order). */
function webCatalog(current, lang) {
  const data = JSON.parse(current)
  data.error = Object.fromEntries(entries.map((e) => [e.id, lang === 'en' ? e.en : e.zh]))
  return `${JSON.stringify(data, null, 2)}\n`
}

const catalogPath = join(root, 'Hikki/Resources/Localization/Localizable.xcstrings')
const outputs = [
  [join(root, 'HikkiCore/Sources/Errors/ErrorCode.swift'), swiftCore],
  [join(root, 'Hikki/Sources/Generated/ErrorMessages.swift'), swiftMessages],
  [join(root, 'editor/src/generated/errors.ts'), ts],
  [join(root, 'bff/src/generated/errors.ts'), bff],
  [catalogPath, nativeCatalog(readFileSync(catalogPath, 'utf8'))],
  ...['en', 'zh-Hans'].map((lang) => {
    const path = join(root, `editor/src/locales/${lang}.json`)
    return [path, webCatalog(readFileSync(path, 'utf8'), lang)]
  })
]

let stale = []
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null
  if (current === content) continue
  if (check) stale.push(path.replace(`${root}/`, ''))
  else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, content)
  }
}
if (check && stale.length) {
  console.error(`errors: stale — run \`make errors\`:\n  ${stale.join('\n  ')}`)
  process.exit(1)
}
console.log(
  check ? `errors: ok (${entries.length} codes)` : `errors: ${entries.length} codes written`
)
