#!/usr/bin/env node
// Generates the keyboard-shortcut registry from design/shortcuts.json: a Swift `Shortcut` enum (the native
// menus bind and display them) and `editor/src/generated/shortcuts.ts` (the page matches keydown events and
// shows the same labels). `--check` fails when either output is stale.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(readFileSync(join(root, 'design/shortcuts.json'), 'utf8'))
const swiftOut = join(root, 'Hikki/Sources/Generated/Shortcuts.swift')
const tsOut = join(root, 'editor/src/generated/shortcuts.ts')
const check = process.argv.includes('--check')

const MODIFIERS = ['control', 'option', 'shift', 'command'] // display order: ⌃⌥⇧⌘
const GLYPH = { control: '⌃', option: '⌥', shift: '⇧', command: '⌘' }
const NAMED = {
  arrowUp: { glyph: '↑', swift: '.upArrow', dom: 'ArrowUp' },
  arrowDown: { glyph: '↓', swift: '.downArrow', dom: 'ArrowDown' },
  arrowLeft: { glyph: '←', swift: '.leftArrow', dom: 'ArrowLeft' },
  arrowRight: { glyph: '→', swift: '.rightArrow', dom: 'ArrowRight' },
  tab: { glyph: '⇥', swift: '.tab', dom: 'Tab' },
  return: { glyph: '↩', swift: '.return', dom: 'Enter' },
  escape: { glyph: '⎋', swift: '.escape', dom: 'Escape' },
  delete: { glyph: '⌫', swift: '.delete', dom: 'Backspace' }
}

const entries = Object.entries(manifest.shortcuts).map(([id, s]) => {
  if (!/^[a-z][A-Za-z0-9]*$/u.test(id)) throw new Error(`bad shortcut id: ${id}`)
  for (const m of s.modifiers)
    if (!MODIFIERS.includes(m)) throw new Error(`${id}: bad modifier ${m}`)
  if (!['app', 'editor', 'both'].includes(s.bound)) throw new Error(`${id}: bad bound ${s.bound}`)
  const named = NAMED[s.key]
  if (!named && s.key.length !== 1) throw new Error(`${id}: bad key ${s.key}`)
  const mods = MODIFIERS.filter((m) => s.modifiers.includes(m))
  const display = mods.map((m) => GLYPH[m]).join('') + (named ? named.glyph : s.key.toUpperCase())
  return { id, key: s.key, mods, bound: s.bound, named, display }
})

// Two shortcuts with the same keys would fight; a page-handled one may share with nothing.
const seen = new Map()
for (const e of entries) {
  const combo = `${e.mods.join('+')}+${e.key}`
  if (seen.has(combo)) throw new Error(`${e.id} and ${seen.get(combo)} share ${e.display}`)
  seen.set(combo, e.id)
}

// Shortcut ids that are Swift keywords need backticks as enum cases and members.
const SWIFT_KEYWORDS = new Set([
  'subscript',
  'default',
  'return',
  'import',
  'in',
  'is',
  'as',
  'self',
  'super',
  'true',
  'false',
  'nil',
  'case',
  'switch',
  'repeat',
  'init',
  'deinit',
  'func',
  'var',
  'let',
  'enum',
  'struct',
  'class',
  'protocol',
  'extension',
  'operator',
  'where',
  'while',
  'for',
  'if',
  'else',
  'do',
  'try',
  'throw',
  'throws',
  'static',
  'public',
  'private',
  'internal',
  'open',
  'any',
  'some'
])
const swiftName = (id) => (SWIFT_KEYWORDS.has(id) ? `\`${id}\`` : id)
const swiftMods = (mods) => (mods.length ? `[${mods.map((m) => `.${m}`).join(', ')}]` : '[]')
const swiftKey = (e) => (e.named ? e.named.swift : `"${e.key}"`)
const swift = `// Generated by scripts/gen-shortcuts.mjs from design/shortcuts.json — do not edit.
import SwiftUI

/// Every keyboard shortcut, defined once (design/shortcuts.json) for the native menus and the editor.
enum Shortcut: String, CaseIterable {
${entries.map((e) => `    case ${swiftName(e.id)}`).join('\n')}

    /// Who handles the key: the native menu (\`app\`), the page (\`editor\` — menus only display it), or
    /// the page when it has focus and the menu otherwise (\`both\`).
    enum Binding { case app, editor, both }

    var binding: Binding {
        switch self {
${entries.map((e) => `        case .${swiftName(e.id)}: .${e.bound}`).join('\n')}
        }
    }

    var keyboardShortcut: KeyboardShortcut {
        switch self {
${entries.map((e) => `        case .${swiftName(e.id)}: KeyboardShortcut(${swiftKey(e)}, modifiers: ${swiftMods(e.mods)})`).join('\n')}
        }
    }

    /// "⌘N", "⇧⌘↓" — for menus that can't bind the key (the editor's shortcuts) and for help text.
    var display: String {
        switch self {
${entries.map((e) => `        case .${swiftName(e.id)}: "${e.display}"`).join('\n')}
        }
    }
}
`

const ts = `// Generated by scripts/gen-shortcuts.mjs from design/shortcuts.json — do not edit.

export type ShortcutId =
${entries.map((e) => `  | '${e.id}'`).join('\n')}

export type Shortcut = {
  /** A character (lower case) or a DOM key name (ArrowUp, Tab…). */
  key: string
  command: boolean
  shift: boolean
  option: boolean
  control: boolean
  /** Who handles it: the native menu, the page, or both (see design/shortcuts.json). */
  bound: 'app' | 'editor' | 'both'
  /** "⌘B", "⇧⌘↓" — the label menus show. */
  display: string
}

export const SHORTCUTS: Record<ShortcutId, Shortcut> = {
${entries
  .map(
    (e) =>
      `  ${e.id}: { key: '${e.named ? e.named.dom : e.key}', command: ${e.mods.includes('command')}, shift: ${e.mods.includes('shift')}, option: ${e.mods.includes('option')}, control: ${e.mods.includes('control')}, bound: '${e.bound}', display: '${e.display}' }`
  )
  .join(',\n')}
}
`

function emit(path, content) {
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`stale: ${path} — run \`make shortcuts\``)
      process.exitCode = 1
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
}
emit(swiftOut, swift)
emit(tsOut, ts)
if (!check) console.log(`shortcuts: ${entries.length} → Swift + TS`)
