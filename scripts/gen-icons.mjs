#!/usr/bin/env node
// Copies the Phosphor icons listed in design/icons.json into HikkiUI's asset catalog (vector, template
// rendering) and generates the type-safe `Icon` enum. `--check` fails when the outputs are stale.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(readFileSync(join(root, 'design/icons.json'), 'utf8'))
// The editor's own copy of the Phosphor package (a dependency of apps/editor/; the workspace may hoist it to the root).
const source = [
  join(root, 'apps/editor/node_modules/@phosphor-icons/core/assets'),
  join(root, 'node_modules/@phosphor-icons/core/assets')
].find((dir) => existsSync(dir))
if (!source) throw new Error('gen-icons: @phosphor-icons/core is not installed (run bun install)')
const catalog = join(root, 'HikkiUI/Resources/Icons.xcassets')
const swiftOut = join(root, 'HikkiUI/Sources/Generated/Icons.swift')
const webOut = join(root, 'apps/editor/src/generated/icons.ts')
const check = process.argv.includes('--check')

const camel = (s) => s.replace(/-([a-z0-9])/gu, (_, c) => c.toUpperCase())
const pascal = (s) => camel(s).replace(/^[a-z]/u, (c) => c.toUpperCase())
const base = manifest.baseWeight
// The native side's icons: an asset and a Swift case each. `"native": false` keeps an icon to the page (its wrapper
// below still names an SF Symbol for iOS).
const entries = Object.entries(manifest.icons)
  .filter(([, opts]) => opts.native !== false)
  .flatMap(([name, opts]) =>
    (opts.weights ?? [base]).map((weight) => {
      // Phosphor's own file naming; our asset/case names are unsuffixed for the base weight.
      const file = weight === 'regular' ? `${name}.svg` : `${name}-${weight}.svg`
      const asset = weight === base ? name : `${name}-${weight}`
      const sf =
        typeof opts.sf === 'string'
          ? weight === base
            ? opts.sf
            : null
          : (opts.sf?.[weight] ?? null)
      return { name, weight, file, asset, swift: camel(asset), sf }
    })
  )

/**
 * Asset catalog entries: SVG with a concrete fill (Xcode's renderer ignores currentColor), template rendering,
 * and an intrinsic 24pt size — Phosphor ships viewBox-only SVGs, which Xcode sizes at 256pt, and places that
 * ignore `.frame` (toolbar labels) then showed giant icons.
 */
function catalogFiles() {
  const files = new Map([
    [join(catalog, 'Contents.json'), '{"info":{"author":"xcode","version":1}}\n']
  ])
  for (const e of entries) {
    const path = join(source, e.weight, e.file)
    if (!existsSync(path)) throw new Error(`unknown Phosphor icon: ${e.weight}/${e.file}`)
    // Base-weight icons get an outline stroke (strokeBoost) — Phosphor has no weight between regular and bold.
    const boost =
      e.weight === base && manifest.strokeBoost
        ? `stroke="#000000" stroke-width="${manifest.strokeBoost}" stroke-linejoin="round" `
        : ''
    const svg = readFileSync(path, 'utf8')
      .replace(/fill="currentColor"/gu, 'fill="#000000"')
      .replace('<svg ', `<svg width="24" height="24" ${boost}`)
    const dir = join(catalog, `${e.asset}.imageset`)
    files.set(join(dir, e.file), svg)
    files.set(
      join(dir, 'Contents.json'),
      `${JSON.stringify({
        images: [{ filename: e.file, idiom: 'universal' }],
        info: { author: 'xcode', version: 1 },
        properties: {
          'preserves-vector-representation': true,
          'template-rendering-intent': 'template'
        }
      })}\n`
    )
  }
  return files
}

function swift() {
  const cases = entries.map((e) => `    case ${e.swift} = "${e.asset}"`).join('\n')
  const symbols = entries
    .filter((e) => e.sf)
    .map((e) => `        case .${e.swift}: "${e.sf}"`)
    .join('\n')
  return `// GENERATED by scripts/gen-icons.mjs from design/icons.json — do not edit; run \`make icons\`.
// swift-format-ignore-file

import SwiftUI

/// The native shell's icons: SF Symbols where design/icons.json names one, else the bundled Phosphor asset
/// (the web editor uses the Phosphor names via @phosphor-icons/react).
public nonisolated enum Icon: String, CaseIterable, Sendable {
${cases}

    /// The SF Symbol drawn for this icon, if any.
    public var systemName: String? {
        switch self {
${symbols}
        default: nil
        }
    }

    /// Not resizable: the system sizes it (toolbar and Settings tabs, sidebar and menu labels).
    public var glyph: Image {
        if let systemName { return Image(systemName: systemName) }
        return Image(rawValue, bundle: .module).renderingMode(.template)
    }

    /// Template image: tint with \`.foregroundStyle\`, size with \`.frame\` — resizable, so pair it with
    /// \`.aspectRatio(contentMode: .fit)\` (SF Symbols aren't square).
    public var image: Image {
        if let systemName { return Image(systemName: systemName).resizable() }
        return Image(rawValue, bundle: .module).renderingMode(.template).resizable()
    }
}
`
}

/**
 * The editor's icons under their Phosphor component names: Phosphor's drawing, or on iOS the SF Symbol the native
 * side names for the same icon (lib/sf-icons.ts). The editor imports these instead of @phosphor-icons/react.
 */
function web() {
  const lines = Object.entries(manifest.icons).map(([icon, opts]) => {
    const name = `${pascal(icon)}Icon`
    const sf = typeof opts.sf === 'string' ? opts.sf : (opts.sf?.[base] ?? null)
    return `export const ${name}: Icon = sfIcon(Phosphor.${name}, ${sf ? JSON.stringify(sf) : 'null'})`
  })
  return `// GENERATED by scripts/gen-icons.mjs from design/icons.json — do not edit; run \`make icons\`.
// The editor's icons under their Phosphor names: Phosphor's drawing, or on iOS the SF Symbol named for the same icon
// (lib/sf-icons.ts). Import these, never @phosphor-icons/react directly.
import type { Icon } from '@phosphor-icons/react'
import * as Phosphor from '@phosphor-icons/react'

import { sfIcon } from '../lib/sf-icons'

${lines.join('\n')}
`
}

const outputs = catalogFiles()
outputs.set(swiftOut, swift())
outputs.set(webOut, web())
let stale = false
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null
  if (current === content) continue
  if (check) {
    console.error(`stale: ${path.replace(`${root}/`, '')} — run \`make icons\``)
    stale = true
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, content)
  }
}
// Imagesets no longer listed in the manifest.
if (existsSync(catalog)) {
  const wanted = new Set(entries.map((e) => `${e.asset}.imageset`))
  for (const dir of readdirSync(catalog).filter((d) => d.endsWith('.imageset') && !wanted.has(d))) {
    if (check) {
      console.error(`stale: ${dir} is not in design/icons.json`)
      stale = true
    } else rmSync(join(catalog, dir), { recursive: true })
  }
}
// Files left inside kept imagesets (e.g. the old SVG after a weight change).
for (const e of entries) {
  const dir = join(catalog, `${e.asset}.imageset`)
  if (!existsSync(dir)) continue
  for (const file of readdirSync(dir).filter((name) => !outputs.has(join(dir, name)))) {
    if (check) {
      console.error(`stale: ${e.asset}.imageset/${file}`)
      stale = true
    } else rmSync(join(dir, file))
  }
}
if (stale) process.exit(1)
